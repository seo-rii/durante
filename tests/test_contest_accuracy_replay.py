"""Reproduce the contest clock comparison from the preregistration and the original executions."""
from collections import Counter
import hashlib
import json
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments"))
from contest_accuracy import corpus
from deadline_accuracy.verify import verify
from shape_calibration.verify_combined import unpack

RESULTS = ROOT / "experiments/results/gce-contest-deadlines"
PLAN = ROOT / "experiments/contest_accuracy/plan.json"


class ContestRegistration(unittest.TestCase):
    def test_regenerates_every_registered_input_and_answer(self):
        registration = PLAN.read_bytes()
        self.assertEqual(hashlib.sha256(registration).hexdigest(),
                         "b6944543bffd6d9500e022109195902b80fae766cec8cdc0a1d0d08decf2f3f7")
        plan = json.loads(registration)
        corpus.expand(plan)
        hashes = set()
        for case in plan["cases"]:
            with self.subTest(case=case["case_id"]):
                for name in ("stdin", "stdout"):
                    text = case[name].encode()
                    self.assertTrue(text.endswith(b"\n"))
                    self.assertEqual(hashlib.sha256(text).hexdigest(), case[name + "_sha256"])
                hashes.add(case["stdin_sha256"])
        self.assertEqual(len(hashes), 16)

    def test_regeneration_rejects_changed_expected_output_digest(self):
        case = json.loads(PLAN.read_bytes())["cases"][0]
        case["stdout_sha256"] = "0" * 64
        with self.assertRaisesRegex(ValueError, "generated bytes differ"):
            corpus.expand({"cases": [case]})


class ContestArchive(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        temp = tempfile.TemporaryDirectory()
        cls.addClassCleanup(temp.cleanup)
        cls.output = unpack(RESULTS / "output.tar.xz", Path(temp.name))

    def test_reconstructs_all_held_out_decisions_and_costs(self):
        result = verify(self.output, "exact-one", contest=True)
        self.assertEqual(result, json.loads((RESULTS / "metrics.json").read_bytes()))
        cases = result["cases"]
        self.assertEqual(Counter(case["program"] for case in cases.values()),
                         {"wall": 3, "rice": 3, "money": 3, "plane": 3})
        self.assertEqual({c["cohort"] for c in cases.values()}, {"prospective"})
        self.assertEqual({c["program"] for c in result["seeds"].values()}, {"wall", "rice", "money", "plane"})
        self.assertEqual(len(result["seeds"]), 4)
        summary = json.loads((self.output / "summary.json").read_bytes())
        native_pids = {row["pid"] for row in summary["native"]}
        self.assertEqual(len(native_pids), result["native_runs"])
        self.assertEqual(Counter(row["case_id"] for row in summary["native"]), {case: 9 for case in cases})
        self.assertEqual(len(native_pids), 108)

        pids = []
        payments = []
        for name, case in cases.items():
            with self.subTest(case=name):
                native = case["baseline_paid_cpu_ns"]
                extra = case["extra_ns"]
                self.assertEqual(len(extra), int(native == 0))
                self.assertEqual(case["packet_exact_ns"], native or extra[0])
                payments.extend(extra)
                prediction = case["baseline_ns"]
                by_ms = {}
                for percent in (85, 100, 115):
                    ms = max(1, (prediction * percent + 99_999_999) // 100_000_000)
                    by_ms.setdefault(ms, []).append(percent)
                fixed = {4, 12, 32}
                self.assertEqual([p["limit_ms"] for p in case["deadlines"]], sorted(fixed | by_ms.keys()))
                for point in case["deadlines"]:
                    ms = point["limit_ms"]
                    self.assertEqual(point["fixed"], ms in fixed)
                    self.assertEqual(point["adaptive_percent"], by_ms.get(ms, []))
                    for arm in ("baseline", "exact"):
                        pids.append(point[arm]["pid"])
                    self.assertEqual(point["exact"]["preflight_ns"], case["packet_exact_ns"])
        totals = result["totals"]["all"]
        self.assertEqual((totals["exact_extra_runs"], totals["exact_extra_cpu_ns"]),
                         (len(payments), sum(payments)))
        self.assertEqual(totals["baseline_paid_cpu_ns"], sum(c["baseline_paid_cpu_ns"] for c in cases.values()))
        self.assertEqual(len(set(pids)), len(pids))
        self.assertTrue(native_pids.isdisjoint(pids))
        self.assertEqual(len(pids), 2 * totals["deadlines"]["all"]["limits"])

        # In this collection all holdouts already had an exact baseline anchor.
        # The two arms share these anchors and still enforce each limit in separate processes.
        self.assertEqual((totals["baseline_paid_runs"], totals["exact_extra_runs"]), (12, 0))
        self.assertEqual(totals["deadlines"]["all"]["changed"], 0)
        wall = next(p for p in cases["wall/crossed_intervals"]["deadlines"] if p["limit_ms"] == 12)
        self.assertTrue(wall["fixed"])
        self.assertEqual(wall["native_tle_reps"], 3)
        self.assertTrue(wall["exact"]["tle"])
        self.assertFalse(wall["exact"]["majority_match"])

    def test_refuses_previous_study_registration(self):
        with self.assertRaisesRegex(ValueError, "different registration"):
            verify(self.output, "exact-one")

    def test_rejects_other_stdin_at_registered_path(self):
        first = json.loads(PLAN.read_bytes())["cases"][0]
        path = self.output / "inputs" / first["stdin_sha256"]
        original = path.read_bytes()
        try:
            path.write_bytes(original + b"\n")
            with self.assertRaisesRegex(ValueError, "different input supplied"):
                verify(self.output, "exact-one", contest=True)
        finally:
            path.write_bytes(original)
