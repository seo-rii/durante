"""Build the compact contest registration or reproduce its exact stdin and expected stdout."""
import argparse
import hashlib
import json
from pathlib import Path

if __package__:
    from . import money, plane, rice, wall
else:
    import money, plane, rice, wall

HERE = Path(__file__).resolve().parent
GENERATORS = {"rice": rice, "wall": wall, "money": money, "plane": plane}


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def register(binaries):
    rules = json.loads((HERE / "rules.json").read_bytes())
    cases = []
    for program, module in GENERATORS.items():
        binary_sha = sha((binaries / program).read_bytes())
        for index, name in enumerate(module.CASES):
            stdin, stdout = module.make(name)
            seed = index == 0
            cases.append(dict(case_id=f"{program}/{name}", program=program, variant=name,
                              split="calibration" if seed else "holdout",
                              cohort="calibration" if seed else "prospective",
                              binary_sha256=binary_sha, stdin_sha256=sha(stdin.encode()),
                              stdout_sha256=sha(stdout.encode()), fixed_limits_ms=[] if seed else [4, 12, 32]))
    return dict(schema=1, authority="diagnostic_only", poll_ms=5, timeout_ms=120000, native_rounds=9,
                probe_sha256=rules["probe_sha256"], deadline_percent=[85, 100, 115], cases=cases)


def expand(plan, generators=GENERATORS):
    """Verify generated bytes against the registration before supplying them to either the runner or scorer."""
    for case in plan["cases"]:
        program, variant = case["program"], case["variant"]
        if case["case_id"] != f"{program}/{variant}":
            raise ValueError("inconsistent contest case identity")
        stdin, stdout = generators[program].make(variant)
        if sha(stdin.encode()) != case["stdin_sha256"] or sha(stdout.encode()) != case["stdout_sha256"]:
            raise ValueError("generated bytes differ from registered contest case " + case["case_id"])
        case.update(stdin=stdin, stdout=stdout)


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--binaries", type=Path, required=True)
    print(json.dumps(register(cli.parse_args().binaries), indent=2))
