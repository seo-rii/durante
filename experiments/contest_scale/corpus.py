"""Register and rematerialize the exact inputs for the longer contest timing study."""
import argparse
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from contest_accuracy import wall
from contest_accuracy.corpus import sha
from contest_batch import variants as batch
from contest_scale import variants


CONTROLS = {("wall", "crossed_intervals"): wall.make, ("scrivener", "prefix_forks"): batch.editor}


def make(program, name):
    fn = CONTROLS.get((program, name), variants.GENERATE[program])
    return fn(name)


def register(binaries):
    rules = json.loads((HERE / "rules.json").read_bytes())
    prospective = [(program, name) for program, names in variants.CASES.items() for name in names]
    cases = []
    for program, name in prospective + list(CONTROLS):
        stdin, stdout = make(program, name)
        previous = (program, name) in CONTROLS
        cases.append(dict(case_id=f"{program}/{name}", program=program, variant=name, split="holdout",
                          cohort="previous" if previous else "prospective",
                          binary_sha256=sha((binaries / program).read_bytes()), stdin_sha256=sha(stdin.encode()),
                          stdout_sha256=sha(stdout.encode()), fixed_limits_ms=[12, 13, 14] if previous else [50, 100, 200, 400]))
    return dict(schema=1, authority="diagnostic_only", poll_ms=5, timeout_ms=120000, native_rounds=11,
                probe_sha256=rules["probe_sha256"], deadline_percent=[85, 100, 115], cases=cases)


def expand(plan):
    for case in plan["cases"]:
        program, name = case["program"], case["variant"]
        if case["case_id"] != f"{program}/{name}":
            raise ValueError("inconsistent contest scale case identity")
        stdin, stdout = make(program, name)
        if sha(stdin.encode()) != case["stdin_sha256"] or sha(stdout.encode()) != case["stdout_sha256"]:
            raise ValueError("generated bytes differ from registered scale case " + case["case_id"])
        case.update(stdin=stdin, stdout=stdout)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binaries", type=Path, required=True)
    print(json.dumps(register(parser.parse_args().binaries), indent=2))
