"""Freeze or reproduce the exact-input cases for the two-boot round-robin calibration comparison."""
import argparse
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from contest_accuracy import wall
from contest_accuracy.corpus import sha
from contest_batch import variants
from contest_warm import scrivener


CONTROLS = {("scrivener", "distant_versions"): scrivener.make, ("wall", "crossed_intervals"): wall.make}


def make(program, variant):
    return CONTROLS.get((program, variant), variants.GENERATE[program])(variant)


def register(binaries):
    cases = []
    ids = [(program, variant) for program, names in variants.CASES.items() for variant in names] + list(CONTROLS)
    for program, variant in ids:
        stdin, stdout = make(program, variant)
        fixed = [5, 12, 25, 50]
        if (program, variant) == ("scrivener", "distant_versions"):
            fixed = [5, 12, 13, 25, 50]
        cases.append(dict(case_id=f"{program}/{variant}", program=program, variant=variant, split="holdout",
                          cohort="previous" if (program, variant) in CONTROLS else "prospective",
                          binary_sha256=sha((binaries / program).read_bytes()), stdin_sha256=sha(stdin.encode()),
                          stdout_sha256=sha(stdout.encode()), fixed_limits_ms=fixed))
    probe = json.loads((HERE / "rules.json").read_bytes())["probe_sha256"]
    return dict(schema=1, authority="diagnostic_only", poll_ms=5, timeout_ms=120000, native_rounds=11,
                probe_sha256=probe, deadline_percent=[85, 100, 115], cases=cases)


def expand(plan):
    for case in plan["cases"]:
        program, variant = case["program"], case["variant"]
        if case["case_id"] != f"{program}/{variant}":
            raise ValueError("inconsistent batch case identity")
        stdin, stdout = make(program, variant)
        if sha(stdin.encode()) != case["stdin_sha256"] or sha(stdout.encode()) != case["stdout_sha256"]:
            raise ValueError("generated bytes differ from registered batch case " + case["case_id"])
        case.update(stdin=stdin, stdout=stdout)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binaries", type=Path, required=True)
    print(json.dumps(register(parser.parse_args().binaries), indent=2))
